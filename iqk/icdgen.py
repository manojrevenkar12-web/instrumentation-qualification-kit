"""Generate the C++ codecs and the human-readable ICDs from icd/*.yaml.

Generated files are committed: they are configuration items a reviewer reads, and the build does not need
Python. `iqk icd check` (and CI) fails when a committed file differs from what the YAML generates.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from . import icd as I

CPP_OUT = I.ROOT / "cpp" / "gen" / "iqk" / "icd"
DOC_OUT = I.ROOT / "docs" / "icd"

CTYPE = {
    "u8": "std::uint8_t",
    "i8": "std::int8_t",
    "u16": "std::uint16_t",
    "i16": "std::int16_t",
    "u32": "std::uint32_t",
    "i32": "std::int32_t",
    "u48": "std::uint64_t",
    "u64": "std::uint64_t",
    "i64": "std::int64_t",
}
BANNER = "// Generated by iqk.icdgen from icd/{key}.yaml ({icd} {version}). Do not edit.\n"


def camel(s: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[_\-]", s))


def _num(x: float) -> str:
    r = repr(float(x))
    return r if ("e" in r or "." in r) else r + ".0"


def _struct(name: str, fields: tuple[I.Field, ...], msg: I.Message | None, arr_struct: str | None) -> list[str]:
    out = [f"struct {name} {{"]
    if msg is not None:
        out.append(f"  static constexpr std::uint32_t kId = 0x{msg.id:X}U;")
        if msg.array is None:
            out.append(f"  static constexpr std::size_t kSize = {msg.fixed_size};")
        else:
            out.append(f"  static constexpr std::size_t kFixedSize = {msg.fixed_size};")
            out.append(f"  static constexpr std::size_t kRecordSize = {msg.record_size};")
            out.append(f"  static constexpr std::size_t kMaxRecords = {msg.array.max};")
            out.append(f"  static constexpr std::size_t kMaxSize = {msg.max_size};")
        if msg.rate_hz:
            out.append(f"  static constexpr double kRateHz = {_num(msg.rate_hz)};")
        if msg.per_node:
            out.append(
                "  [[nodiscard]] static constexpr std::uint32_t can_id(std::uint8_t node) noexcept { return kId + node; }"
            )
    for f in fields:
        if f.type == "array":
            out.append(f"  {CTYPE[f.count]} {f.name}_count{{}};  // number of valid {f.name}")
            out.append(f"  std::array<{arr_struct}, {f.max}> {f.name}{{}};")
            continue
        doc = f"  // {f.unit}" if f.unit else ""
        out.append(f"  {CTYPE[f.type]} {f.name}{{}};{doc}")
    for f in fields:
        t = CTYPE.get(f.type, "")
        for b, pos in f.bits.items():
            out.append(
                f"  [[nodiscard]] constexpr bool {b}() const noexcept {{ return (({f.name} >> {pos}U) & 1U) != 0U; }}"
            )
            out.append(
                f"  constexpr void set_{b}(bool v) noexcept {{ {f.name} = static_cast<{t}>(v ? ({f.name} | (1ULL << {pos}U))"
                f" : ({f.name} & ~(1ULL << {pos}U))); }}"
            )
        if f.scale is not None:
            out.append(f"  static constexpr double k{camel(f.name)}Scale = {_num(f.scale)};")
            out.append(
                f"  [[nodiscard]] constexpr double {f.name}_eng() const noexcept {{ return static_cast<double>({f.name}) * {_num(f.scale)}; }}"
            )
    out.append("};")
    return out


def _codec(name: str, msg: I.Message, order: str, arr_struct: str | None) -> list[str]:
    o = "wire::Order::little" if order == "little" else "wire::Order::big"
    fields = (*msg.header, *msg.fields)
    size_expr = (
        "m.kSize" if msg.array is None else f"m.kFixedSize + std::size_t{{m.{msg.array.name}_count}} * m.kRecordSize"
    )
    enc = [
        f"[[nodiscard]] inline std::size_t encode(const {name}& m, std::span<std::uint8_t> out) noexcept {{",
    ]
    if msg.array is not None:
        enc.append(f"  if (m.{msg.array.name}_count > m.kMaxRecords) {{ return 0; }}")
    enc.append(f"  const std::size_t n = {size_expr};")
    enc.append("  if (out.size() < n) { return 0; }")
    enc.append("  std::size_t off = 0;")
    dec = [
        f"[[nodiscard]] inline bool decode(std::span<const std::uint8_t> in, {name}& m) noexcept {{",
    ]
    if msg.array is None:
        dec.append(f"  if (in.size() != {name}::kSize) {{ return false; }}")
    else:
        dec.append(f"  if (in.size() < {name}::kFixedSize) {{ return false; }}")
    dec.append("  std::size_t off = 0;")
    for f in fields:
        if f.type == "array":
            cs = I.SIZES[f.count]
            enc.append(f"  wire::put(out, off, m.{f.name}_count, {cs}, {o});")
            enc.append(f"  off += {cs};")
            enc.append(f"  for (std::size_t i = 0; i < m.{f.name}_count; ++i) {{")
            enc.append(f"    const auto& r = m.{f.name}[i];")
            dec.append(f"  m.{f.name}_count = static_cast<{CTYPE[f.count]}>(wire::get(in, off, {cs}, {o}));")
            dec.append(f"  off += {cs};")
            dec.append(
                f"  if (m.{f.name}_count > {name}::kMaxRecords || in.size() != {name}::kFixedSize + std::size_t{{m.{f.name}_count}} * {name}::kRecordSize) {{ return false; }}"
            )
            dec.append(f"  for (std::size_t i = 0; i < m.{f.name}_count; ++i) {{")
            dec.append(f"    auto& r = m.{f.name}[i];")
            for g in f.of:
                enc.append(f"    wire::put(out, off, wire::to_raw(r.{g.name}), {g.size}, {o});")
                enc.append(f"    off += {g.size};")
                dec.append(f"    r.{g.name} = wire::from_raw<{CTYPE[g.type]}>(wire::get(in, off, {g.size}, {o}));")
                dec.append(f"    off += {g.size};")
            enc.append("  }")
            dec.append("  }")
            continue
        enc.append(f"  wire::put(out, off, wire::to_raw(m.{f.name}), {f.size}, {o});")
        enc.append(f"  off += {f.size};")
        if f.type == "u48":
            dec.append(f"  m.{f.name} = wire::get(in, off, 6, {o});")
        else:
            dec.append(f"  m.{f.name} = wire::from_raw<{CTYPE[f.type]}>(wire::get(in, off, {f.size}, {o}));")
        dec.append(f"  off += {f.size};")
    enc += ["  return off;", "}"]
    dec += ["  return off == in.size();", "}"]

    rng = [f"[[nodiscard]] inline bool in_range(const {name}& m) noexcept {{"]
    checks = []
    for f in fields:
        if f.range is None or f.type == "array":
            continue
        lo, hi = f.range
        s = f.scale or 1.0
        # Compare in raw units: the ICD range in engineering units, converted once, rounded inward.
        rlo, rhi = _raw_limits(lo, hi, s)
        tlo, thi = f.raw_bounds()
        if rlo > tlo:
            checks.append(f"m.{f.name} >= {rlo}LL")
        if rhi < thi:
            checks.append(f"m.{f.name} <= {rhi}LL")
    if not checks:
        rng[0] = f"[[nodiscard]] inline bool in_range(const {name}& /*m*/) noexcept {{"
    rng.append("  return " + (" &&\n         ".join(checks) if checks else "true") + ";")
    rng.append("}")
    return enc + [""] + dec + [""] + rng


def _raw_limits(lo: float, hi: float, scale: float) -> tuple[int, int]:
    """The ICD range in raw units, rounded inward so a raw value inside is inside in engineering units."""
    import math

    return math.ceil(round(lo / scale, 9)), math.floor(round(hi / scale, 9))


def cpp_header(key: str) -> str:
    d = I.load(key)
    ns = key
    lines = [
        BANNER.format(key=key, icd=d.icd, version=d.version),
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "#include <string_view>",
        "",
        '#include "iqk/wire.hpp"',
        "",
        f"namespace iqk::icd::{ns} {{",
        "",
        f'inline constexpr std::string_view kIcd = "{d.icd}";',
        f'inline constexpr std::string_view kVersion = "{d.version}";',
        "",
    ]
    transport = {k: v for k, v in d.transport.items() if isinstance(v, int) and not isinstance(v, bool)}
    lines += _extras({**transport, **d.extra}) + [""]
    for m in d.messages:
        name = camel(m.name)
        arr_struct = None
        if m.array is not None:
            arr_struct = f"{name}{camel(m.array.name)}"
            lines += _struct(arr_struct, m.array.of, None, None) + [""]
        lines += _struct(name, (*m.header, *m.fields), m, arr_struct) + [""]
        lines += _codec(name, m, d.byte_order, arr_struct) + [""]
    lines.append(f"}}  // namespace iqk::icd::{ns}")
    return "\n".join(lines) + "\n"


def _const(name: str, v) -> str | None:
    if isinstance(v, bool):
        return f"inline constexpr bool {name} = {'true' if v else 'false'};"
    if isinstance(v, int):
        return f"inline constexpr std::int64_t {name} = {v};"
    if isinstance(v, float):
        return f"inline constexpr double {name} = {_num(v)};"
    if isinstance(v, str):
        return f'inline constexpr std::string_view {name} = "{v}";'
    if isinstance(v, list) and v and all(isinstance(x, int) and not isinstance(x, bool) for x in v):
        return f"inline constexpr std::array<std::int64_t, {len(v)}> {name}{{{', '.join(str(x) for x in v)}}};"
    if isinstance(v, list) and v and all(isinstance(x, float | int) for x in v):
        return f"inline constexpr std::array<double, {len(v)}> {name}{{{', '.join(_num(x) for x in v)}}};"
    if isinstance(v, list) and v and all(isinstance(x, str) for x in v):
        items = ", ".join(f'"{x}"' for x in v)
        return f"inline constexpr std::array<std::string_view, {len(v)}> {name}{{{items}}};"
    return None


def _extras(extra: dict) -> list[str]:
    out = []
    for k, v in extra.items():
        if k == "registers":
            for r in v:
                n = "kReg" + camel(r["name"])
                out.append(f"inline constexpr std::uint16_t {n}Index = 0x{r['index']:X}U;")
                out.append(f"inline constexpr std::uint8_t {n}Sub = {r['sub']}U;")
            continue
        c = _const("k" + camel(k), v)
        if c:
            out.append(c)
    return out


def config_header() -> str:
    cfg = yaml.safe_load((I.ROOT / "config" / "unit.yaml").read_text())
    lines = [
        "// Generated by iqk.icdgen from config/unit.yaml. Do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace iqk::cfg {",
    ]
    for section, values in cfg.items():
        lines += ["", f"namespace {section} {{"]
        for k, v in values.items():
            c = _const(k, v)
            if c is None:
                raise ValueError(f"config/unit.yaml: {section}.{k} has no C++ form")
            lines.append(c)
        lines.append(f"}}  // namespace {section}")
    lines += ["", "}  // namespace iqk::cfg", ""]
    return "\n".join(lines)


def doc(key: str) -> str:
    d = I.load(key)
    t = d.transport
    out = [
        f"# {d.icd} {d.version}: {d.title}",
        "",
        f"Generated from [`icd/{key}.yaml`](../../icd/{key}.yaml). Do not edit.",
        "",
        f"Byte order: **{d.byte_order}-endian**. Transport: {', '.join(f'{k} {v}' for k, v in t.items())}.",
        "",
    ]
    for k, v in d.extra.items():
        if k == "registers":
            continue
        out.append(f"- `{k}`: {v}")
    if d.extra:
        out.append("")
    if "registers" in d.extra:
        out += [
            "## Registers",
            "",
            "Per-channel registers are at index + channel (0..channels-1).",
            "",
            "| Index | Sub | Name | Values | Notes |",
            "|---|---:|---|---|---|",
        ]
        for r in d.extra["registers"]:
            idx = f"0x{r['index']:04X}" + (" + ch" if r.get("per_channel") else "")
            vals = (
                f"{r['range'][0]}..{r['range'][1]}"
                if "range" in r
                else f"one of `{r['values_from']}`"
                if "values_from" in r
                else ""
            )
            out.append(f"| {idx} | {r['sub']} | {r['name']} | {vals} | {r.get('description', '')} |")
        out.append("")
    for m in d.messages:
        size = (
            f"{m.fixed_size} bytes"
            if m.array is None
            else f"{m.fixed_size} + {m.record_size} × n bytes (n ≤ {m.array.max})"
        )
        idtxt = f"0x{m.id:X}" + (" + node id" if m.per_node else "")
        rate = f", {m.rate_hz} Hz" if m.rate_hz else ""
        out += [f"## {m.name}", "", f"Id {idtxt}, {m.direction.replace('_', ' ')}{rate}, {size}.", ""]
        if m.description:
            out += [m.description, ""]
        out += ["| Offset | Field | Type | Scale | Unit | Range | Notes |", "|---:|---|---|---|---|---|---|"]
        off = 0
        for f in (*m.header, *m.fields):
            if f.type == "array":
                out.append(f"| {off} | {f.name} count | {f.count} | | | 0..{f.max} | |")
                off += I.SIZES[f.count]
                r = 0
                for g in f.of:
                    out.append(
                        f"| +{r} | {f.name}[i].{g.name} | {g.type} | {g.scale or ''} | {g.unit} | | {_notes(g)} |"
                    )
                    r += g.size
                continue
            rng = f"{f.range[0]:g} .. {f.range[1]:g}" if f.range else ""
            out.append(f"| {off} | {f.name} | {f.type} | {f.scale or ''} | {f.unit} | {rng} | {_notes(f)} |")
            off += f.size
        out.append("")
    return "\n".join(out)


def _notes(f: I.Field) -> str:
    bits = ", ".join(f"bit {p} {b}" for b, p in f.bits.items())
    return "; ".join(x for x in (f.description.replace("|", "/"), bits) if x)


def outputs() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for k in I.keys():
        files[CPP_OUT / f"{k}.hpp"] = cpp_header(k)
        files[DOC_OUT / f"{k}.md"] = doc(k)
    files[CPP_OUT.parent / "config.hpp"] = config_header()
    files[CPP_OUT / "codec_dispatch.hpp"] = dispatch_header()
    return files


def write() -> list[Path]:
    changed = []
    for p, text in outputs().items():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
            changed.append(p)
    return changed


def drift() -> list[Path]:
    """Committed generated files that differ from what the YAML generates."""
    return [p for p, text in outputs().items() if not p.exists() or p.read_text() != text]


def dispatch_header() -> str:
    """codec_decode / codec_encode over every message, for iqkctl and the C++/Python parity tests."""
    lines = [
        "// Generated by iqk.icdgen from icd/*.yaml. Do not edit.",
        "#pragma once",
        "",
        "#include <charconv>",
        "#include <cstdint>",
        "#include <map>",
        "#include <span>",
        "#include <string>",
        "#include <string_view>",
        "#include <vector>",
        "",
    ]
    for k in I.keys():
        lines.append(f'#include "iqk/icd/{k}.hpp"')
    lines += [
        "",
        "namespace iqk::icd {",
        "",
        "namespace detail {",
        "template <class T>",
        "bool parse_field(const std::map<std::string, std::string>& kv, const std::string& key, T& out) {",
        "  const auto it = kv.find(key);",
        "  if (it == kv.end()) { return false; }",
        "  const std::string& s = it->second;",
        "  const auto r = std::from_chars(s.data(), s.data() + s.size(), out);",
        "  return r.ec == std::errc{} && r.ptr == s.data() + s.size();",
        "}",
        "}  // namespace detail",
        "",
        "// Decodes a payload into key=value lines (raw integer values). False if the ICD rejects it.",
        "inline bool codec_decode(std::string_view icd, std::string_view msg, std::span<const std::uint8_t> in, std::string& out) {",
    ]
    for k in I.keys():
        d = I.load(k)
        for m in d.messages:
            n = camel(m.name)
            lines.append(f'  if (icd == "{k}" && msg == "{m.name}") {{')
            lines.append(f"    {k}::{n} m{{}};")
            lines.append(f"    if (!{k}::decode(in, m)) {{ return false; }}")
            for f in (*m.header, *m.fields):
                if f.type == "array":
                    lines.append(f"    for (std::size_t i = 0; i < m.{f.name}_count; ++i) {{")
                    for g in f.of:
                        lines.append(
                            f'      out += "{f.name}." + std::to_string(i) + ".{g.name}=" + std::to_string(m.{f.name}[i].{g.name}) + "\\n";'
                        )
                    lines.append("    }")
                else:
                    lines.append(f'    out += "{f.name}=" + std::to_string(m.{f.name}) + "\\n";')
            lines.append("    return true;")
            lines.append("  }")
    lines += ["  return false;", "}", ""]
    lines += [
        "// Encodes from key=value (raw integers); arrays as name.i.field. Returns the payload, empty on error.",
        "inline std::vector<std::uint8_t> codec_encode(std::string_view icd, std::string_view msg, const std::map<std::string, std::string>& kv) {",
        "  std::vector<std::uint8_t> out;",
    ]
    for k in I.keys():
        d = I.load(k)
        for m in d.messages:
            n = camel(m.name)
            lines.append(f'  if (icd == "{k}" && msg == "{m.name}") {{')
            lines.append(f"    {k}::{n} m{{}};")
            for f in (*m.header, *m.fields):
                if f.type == "array":
                    lines.append("    std::size_t count = 0;")
                    lines.append(
                        f'    while (count < {k}::{n}::kMaxRecords && kv.contains("{f.name}." + std::to_string(count) + ".{f.of[0].name}")) {{'
                    )
                    for g in f.of:
                        lines.append(
                            f'      if (!detail::parse_field(kv, "{f.name}." + std::to_string(count) + ".{g.name}", m.{f.name}[count].{g.name})) {{ return out; }}'
                        )
                    lines.append("      ++count;")
                    lines.append("    }")
                    lines.append(f"    m.{f.name}_count = static_cast<decltype(m.{f.name}_count)>(count);")
                else:
                    lines.append(f'    if (!detail::parse_field(kv, "{f.name}", m.{f.name})) {{ return out; }}')
            size = f"{k}::{n}::kSize" if m.array is None else f"{k}::{n}::kMaxSize"
            lines.append(f"    out.resize({size});")
            lines.append(f"    out.resize({k}::encode(m, out));")
            lines.append("    return out;")
            lines.append("  }")
    lines += ["  return out;", "}", "", "}  // namespace iqk::icd", ""]
    return "\n".join(lines)
